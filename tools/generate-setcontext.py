#!/usr/bin/env python3
"""Regenerate the x86-64 libunwind restore bytes (GNU as/objcopy/nm on x86).

The checked-in header lets Android ARM64 builds use the exact same guest
routine without requiring an x86 assembler in the cross-build toolchain.
"""
from pathlib import Path
import argparse
import subprocess
import tempfile


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--fixture", action="store_true", help="generate/check the synthetic CPU test fixture")
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    source = root / ("tests/guest_setcontext_fixture.S" if args.fixture else "src/guest_setcontext_x86_64.S")
    header = root / ("tests/guest_setcontext_fixture.h" if args.fixture else "src/guest_setcontext_code.h")
    prefix = "driveclub_setcontext_test" if args.fixture else "driveclub_setcontext"
    with tempfile.TemporaryDirectory(prefix="driveclub-setcontext-") as tmp:
        obj, raw = Path(tmp) / "restore.o", Path(tmp) / "restore.bin"
        subprocess.run(["as", "--64", str(source), "-o", str(obj)], check=True)
        subprocess.run(["objcopy", "-O", "binary", "-j", ".text", str(obj), str(raw)], check=True)
        symbols = {}
        for line in subprocess.check_output(["nm", "-n", str(obj)], text=True).splitlines():
            columns = line.split()
            if len(columns) == 3:
                symbols[columns[2]] = int(columns[0], 16)
        begin = symbols[prefix + "_code"]
        end = symbols[prefix + "_end"]
        failure = None if args.fixture else symbols["driveclub_setcontext_failure_target"] - begin
        code = raw.read_bytes()[begin:end]
    body = "\n".join("    " + ",".join(f"0x{x:02x}" for x in code[i:i+12]) + ","
                     for i in range(0, len(code), 12))
    guard = "DRIVECLUB_GUEST_SETCONTEXT_" + ("FIXTURE_H" if args.fixture else "CODE_H")
    name = "guest_setcontext_fixture" if args.fixture else "guest_setcontext_code"
    generated = (f"/* Generated by tools/generate-setcontext.py from {source.name}. */\n"
                 f"#ifndef {guard}\n#define {guard}\n"
                 + ("" if args.fixture else f"#define GUEST_SETCONTEXT_FAILURE_OFFSET {failure}u\n")
                 + f"static const unsigned char {name}[]={{\n" + body + "\n};\n#endif\n")
    if args.check:
        if not header.exists() or header.read_text() != generated:
            raise SystemExit(f"{header.name} does not match its assembly source")
        print(f"PASS: setcontext assembly matches {len(code)} checked-in bytes")
    else:
        header.write_text(generated)
        print(f"Generated {header.name}: {len(code)} bytes" + ("" if args.fixture else f", failure target at {failure}"))


if __name__ == "__main__":
    main()
