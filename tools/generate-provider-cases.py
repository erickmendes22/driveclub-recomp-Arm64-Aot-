#!/usr/bin/env python3
"""Generate resolver cases exclusively from the port's source declarations.

This command has no module/manifest input. The generated public fixture describes
the runtime implementation, never the import set or binary metadata of a game.
"""
from __future__ import annotations

import argparse
import importlib.util
import json
from pathlib import Path
import re
import sys

SPEC = importlib.util.spec_from_file_location("provider_source_audit", Path(__file__).with_name("audit-imports.py"))
audit = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(audit)


def cases(providers: dict, names: dict[str, str]) -> list[dict]:
    result = []
    for nid, declarations in sorted(providers.items()):
        if not declarations:
            continue
        if not re.fullmatch(r"[A-Za-z0-9+-]{11}", nid):
            raise audit.AuditError(f"invalid source provider NID: {nid}")
        for kind in sorted({item["kind"] for item in declarations}):
            if kind not in ("function", "data"):
                raise audit.AuditError(f"invalid source provider kind: {kind}")
            functions = sorted({item["function"] for item in declarations if item["kind"] == kind})
            result.append(dict(name=nid, symbol=names.get(nid) or functions[0], is_data=int(kind == "data")))
    return result


def generate(root: Path, output: Path) -> int:
    names = dict(re.findall(r'\{"([^"\n]+)","([^"\n]+)"\}', (root / "src/import_names.inc").read_text()))
    entries = cases(audit.source_providers(root, names), names)
    lines = ["/* Generated by tools/generate-provider-cases.py from port source declarations only.",
             " * No game module, import inventory, executable metadata or private manifest is read. */",
             "#ifndef RUNTIME_PROVIDER_CASES_H", "#define RUNTIME_PROVIDER_CASES_H",
             "typedef struct { const char *name, *symbol; int is_data; } RuntimeProviderCase;",
             "static const RuntimeProviderCase runtime_provider_cases[] = {"]
    for item in entries:
        lines.append("    {%s, %s, %d}," % (json.dumps(item["name"]), json.dumps(item["symbol"]), item["is_data"]))
    lines += ["};", "#define RUNTIME_PROVIDER_CASE_COUNT (sizeof(runtime_provider_cases)/sizeof(runtime_provider_cases[0]))", "#endif", ""]
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines))
    return len(entries)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args(argv)
    try:
        count = generate(args.root, args.output)
    except (audit.AuditError, OSError, KeyError) as exc:
        print(f"provider cases: {exc}", file=sys.stderr)
        return 2
    print(f"Generated {count} runtime provider cases from port source declarations")
    return 0


if __name__ == "__main__":
    sys.exit(main())
