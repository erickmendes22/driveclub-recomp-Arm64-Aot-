#!/usr/bin/env python3
"""Regenerate checked-in direct-call wrappers from the pinned Vulkan registry.

Input: Vulkan-Headers v1.4.363 registry/vk.xml (SHA256 below).
The build needs no Python/network step: generated .inc/.cmake files are tracked.
"""
from pathlib import Path
import argparse
import hashlib
import re
import xml.etree.ElementTree as ET

REGISTRY_SHA256 = "55ec60950cfb18c3575dcf5fd52741b2bb70eb1e466408f803a91049973ee6fb"

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("registry", type=Path)
    args = parser.parse_args()
    data = args.registry.read_bytes()
    if hashlib.sha256(data).hexdigest() != REGISTRY_SHA256:
        raise SystemExit("Registry must match pinned Vulkan-Headers v1.4.363")
    root = Path(__file__).resolve().parents[2]
    registry = ET.fromstring(data)
    commands = {}
    for entry in registry.findall("./commands/command"):
        proto = entry.find("proto")
        if proto is not None:
            commands[proto.findtext("name")] = entry
    names = set()
    paths = list((root / "gpu/third_party/fsr-vulkan").rglob("*"))
    paths.append(root / "src/vulkan_smoke.c")
    for source in paths:
        if source.suffix not in {".c", ".cpp", ".h", ".hpp"}:
            continue
        names.update(re.findall(r"\b(vk[A-Z]\w*)\s*\(", source.read_text(errors="ignore")))
    names &= commands.keys()
    names |= {"vkCreateInstance", "vkDestroyInstance", "vkGetInstanceProcAddr"}
    special = {"vkCreateInstance", "vkDestroyInstance", "vkGetInstanceProcAddr"}
    generated = ["// Generated by android/tools/generate-vulkan-forwarders.py; do not hand edit.",
                 "// Vulkan-Headers v1.4.363; direct FSR/runtime calls share the selected loader."]
    for name in sorted(names - special):
        entry = commands[name]
        result = entry.find("proto").findtext("type")
        params = []
        arguments = []
        for param in entry.findall("param"):
            if param.get("api") not in (None, "vulkan"):
                continue
            params.append(" ".join("".join(param.itertext()).split()))
            arguments.append(param.findtext("name"))
        generated.append(f"DRIVECLUB_VK_FORWARD({result}, {name},\n    ({', '.join(params)}),\n    ({', '.join(arguments)}))")
    output = root / "android/src/main/cpp/vulkan_forwarders.inc"
    output.write_text("\n".join(generated) + "\n")
    cmake = root / "android/cmake/VulkanCommands.cmake"
    cmake.parent.mkdir(parents=True, exist_ok=True)
    cmake.write_text("# Generated by android/tools/generate-vulkan-forwarders.py\n"
                     "set(DRIVECLUB_VULKAN_COMMANDS\n" +
                     "".join(f"    {name}\n" for name in sorted(names)) + ")\n")
    print(f"Generated {len(names)} Vulkan entry points")

if __name__ == "__main__":
    main()
